    private void adicionarBotoes() {

        Color bege = new Color(255, 230, 195);
        Color marrom = new Color(100, 55, 40);

        jButtonBolos = new JButton("Bolos");
        jButtonPudins = new JButton("Pudins");

        JButton[] botoes = {jButtonBolos, jButtonPudins};

        for (JButton botao : botoes) {

            botao.setBackground(bege);
            botao.setForeground(marrom);
            botao.setFont(new Font("DejaVu Serif", Font.BOLD, 19));
            botao.setFocusPainted(false);
            botao.setPreferredSize(new Dimension(180, 55));

            botao.setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createLineBorder(
                            new Color(220, 190, 155), 2
                    ),
                    BorderFactory.createEmptyBorder(8, 15, 8, 15)
            ));

            botao.setCursor(new java.awt.Cursor(
                    java.awt.Cursor.HAND_CURSOR
            ));
        }

        JPanel painelBotoes = new JPanel(
                new FlowLayout(FlowLayout.CENTER, 25, 20)
        );

        painelBotoes.setBackground(new Color(150, 75, 52));

        painelBotoes.add(jButtonBolos);
        painelBotoes.add(jButtonPudins);

        this.removeAll();
        this.setLayout(new BorderLayout());
        this.add(jPanel1, BorderLayout.CENTER);
        this.add(painelBotoes, BorderLayout.SOUTH);

        this.revalidate();
        this.repaint();

        jButtonBolos.addActionListener(e -> abrirBolos());
        jButtonPudins.addActionListener(e -> abrirPudins());
    }

    private void abrirBolos() {

        JDesktopPane desktop = (JDesktopPane) SwingUtilities.getAncestorOfClass(
                JDesktopPane.class, this
        );

        if (desktop != null) {
            control.CTelaMenu menu
                    = new control.CTelaMenu(desktop);

            menu.abrirBolos();
        }
    }

    private void abrirPudins() {

        JDesktopPane desktop = (JDesktopPane) SwingUtilities.getAncestorOfClass(
                JDesktopPane.class, this
        );

        if (desktop != null) {
            control.CTelaMenu menu
                    = new control.CTelaMenu(desktop);

            menu.abrirPudim();
        }
    }
