private void configurarLayoutResponsivo() {


    JPanel painelLista = new JPanel(new BorderLayout(0, 8));
    painelLista.setBackground(new java.awt.Color(150, 75, 52));

    JPanel painelBotoes = new JPanel(new GridLayout(1, 2, 8, 0));
    painelBotoes.setBackground(new java.awt.Color(150, 75, 52));

    painelLista.add(jTextFieldPesquisa, BorderLayout.NORTH);

    modeloFavoritos = new javax.swing.DefaultListModel<>();
    jListFavoritos = new javax.swing.JList<>(modeloFavoritos);

    javax.swing.JScrollPane scrollFavoritos =
            new javax.swing.JScrollPane(jListFavoritos);

    JPanel painelFavoritos = new JPanel(new BorderLayout());

    painelFavoritos.setBorder(
            javax.swing.BorderFactory.createTitledBorder("★ Favoritos")
    );

    jButtonFavorito = new javax.swing.JButton("☆ Favoritar");
    jButtonFavorito.setBackground(new java.awt.Color(255, 225, 225));

    painelFavoritos.add(jButtonFavorito, BorderLayout.NORTH);
    painelFavoritos.add(scrollFavoritos, BorderLayout.CENTER);

    JSplitPane listas = new JSplitPane(
            JSplitPane.VERTICAL_SPLIT,
            jScrollPane1,
            painelFavoritos
    );

    listas.setResizeWeight(0.70);
    listas.setDividerSize(5);
    listas.setBorder(null);

    painelLista.add(listas, BorderLayout.CENTER);

    painelBotoes.add(jButton1);
    painelBotoes.add(jButton2);

    JPanel painelInferior = new JPanel(new BorderLayout());
    painelInferior.setOpaque(false);
    painelInferior.setBorder(
            javax.swing.BorderFactory.createEmptyBorder(300, 0, 0, 0)
    );

    painelInferior.add(painelBotoes, BorderLayout.CENTER);
    painelLista.add(painelInferior, BorderLayout.SOUTH);

    JSplitPane divisoria = new JSplitPane(
            JSplitPane.HORIZONTAL_SPLIT,
            painelLista,
            jPanel2
    );

    divisoria.setResizeWeight(0.40);
    divisoria.setDividerSize(8);
    divisoria.setBorder(null);
    divisoria.setContinuousLayout(true);

    setLayout(new BorderLayout(10, 0));
    setBorder(new EmptyBorder(10, 10, 10, 10));

    removeAll();
    add(divisoria, BorderLayout.CENTER);

    revalidate();
    repaint();

    SwingUtilities.invokeLater(() -> {
        divisoria.setDividerLocation(0.65);
    });
}


    
